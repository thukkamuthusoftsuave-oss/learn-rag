GENERAL_HANDBOOK = """
================================================================================
GLOBAL EMPLOYEE HANDBOOK (HR-207 CORE)
Effective Date: 2024-01-01 | Status: Active Base Framework
Scope: General policy for all global corporate entities unless overridden by an Entity Annex.
================================================================================

Section 1.1 - Working Hours and Core Schedule
Standard full-time employment comprises 40 hours per week. Core collaboration hours are 10:00 to 16:00 local time. Flexible working arrangements require line manager approval.

Section 2.1 - General Leave Entitlement
Employees receive 20 days of standard annual vacation leave per calendar year, accrued monthly at 1.66 days per completed month. Unused vacation days do not automatically carry over into the next calendar year unless explicitly authorized by regional policy or an Entity Annex.

Section 2.2 - Sick Leave and Medical Absence
Employees are entitled to 10 days of paid sick leave per calendar year. Absences exceeding 3 consecutive working days require a certified medical practitioner note.

Section 3.1 - Probationary Period
The standard probationary period for all new hires across Grades 1 through 5 is 3 calendar months. For Grades 6 and 7, probation is 6 calendar months. Confirmation is contingent on a formal review by the line manager.

Section 4.1 - Standard Notice Periods
Unless specified in an Entity Annex or employment contract:
- During probation: 2 weeks notice by either party.
- Post-probation (Grades 1 to 4): 1 calendar month notice.
- Post-probation (Grades 5 to 7): 2 calendar months notice.

Section 5.1 - Business Travel and Expenses
Expense reimbursements must be submitted within 30 days of incurring the expense with itemized receipts. Mileage allowance is governed by local tax rates.

Section 6.1 - Discretionary Leave and Special Circumstances
Any request for compassionate leave exceeding 5 consecutive business days, career breaks, sabbatical exceptions, or hardship leave advances cannot be approved automatically. All such requests MUST be formally escalated to an HR Business Partner (HRBP) for case-by-case review.
"""

LEAVE_POLICY_2024 = """
================================================================================
GLOBAL PARENTAL & EXTENDED LEAVE POLICY (2024 REVISION)
Document ID: HR-LEAVE-2024-v1.0
Effective Date: 2024-01-01 | Expiration Date: 2024-12-31 | Status: SUPERSEDED
================================================================================

Section 4.1 - Parental Leave Entitlement (2024 Rules)
Primary caregivers are eligible for 12 weeks of paid parental leave at 100% of base salary.
Secondary caregivers are eligible for 2 weeks of paid parental leave at 100% of base salary.
Eligibility requires at least 12 months of continuous service prior to the expected date of birth or adoption placement.

Section 4.2 - Annual Vacation Carry-Over (2024 Rules)
Employees may carry over a maximum of 5 unused vacation days into the following calendar year. Any carried-over days must be utilized before March 31 of the new year, or they are forfeited.

Section 4.3 - Sabbatical Leave (2024 Rules)
Employees with at least 8 years of continuous full-time service may apply for a 4-week unpaid sabbatical. Sabbatical leave must be approved by the Department Head and HRBP.
"""

