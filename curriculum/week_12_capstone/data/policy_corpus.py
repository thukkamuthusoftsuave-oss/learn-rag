INDIA_ENTITY_ANNEX = """
================================================================================
INDIA ENTITY SPECIFIC ANNEX (HR-207-ANNEX-IND)
Effective Date: 2025-01-01 | Status: ACTIVE (STATUTORY OVERRIDE)
Jurisdiction: Soft Suave Technologies India Pvt. Ltd. (Entity Code: IND)
Precedence: This Annex strictly overrides any conflicting clause in the Global Employee Handbook or Global Leave Policies for India employees.
================================================================================

Section 1.1 - Statutory Maternity Benefit
In strict compliance with the Maternity Benefit (Amendment) Act 2017:
All female employees who have completed at least 80 working days in the 12 months preceding delivery are entitled to 26 weeks of fully paid maternity leave for up to two surviving children (12 weeks for third child onward).
Commissioning and adoptive mothers of infants under 3 months receive 12 weeks of fully paid maternity leave.

Section 1.2 - India Paternity Leave
Male employees are entitled to 2 weeks (10 working days) of paid paternity leave, available up to 6 months following childbirth.

Section 2.1 - India Leave Structure & Carry-Over Overrides
India entity employees receive:
- Earned Leave (Privilege Leave): 18 days per annum, accumulative up to a statutory ceiling of 30 days. Unused Earned Leave beyond 30 days is paid out annually.
- Casual Leave: 7 days per annum (cannot be carried over or encashed).
- Sick Leave: 10 days per annum (requires medical certificate if > 2 days).
- Mandatory Festival Holidays: 10 statutory national and festival holidays declared annually.

Section 3.1 - India Notice Period Overrides
Notice periods in the India entity supersede general handbook guidelines:
- During probation (all grades): 30 calendar days notice.
- Confirmed Grades 1 through 4: 60 calendar days (2 months) notice.
- Confirmed Grades 5 through 7: 90 calendar days (3 months) notice.
Payment in lieu of notice requires written approval from the Operations Director.

Section 4.1 - Statutory Gratuity & Severance
Gratuity is payable in accordance with the Payment of Gratuity Act 1972 upon separation after completing a minimum of 5 years of continuous service, calculated as (15 * Last Drawn Basic Salary * Years of Service) / 26.
"""

UK_ENTITY_ANNEX = """
================================================================================
UK ENTITY SPECIFIC ANNEX (HR-207-ANNEX-UK)
Effective Date: 2025-01-01 | Status: ACTIVE (STATUTORY OVERRIDE)
Jurisdiction: Soft Suave UK Operations Ltd. (Entity Code: UK)
Precedence: This Annex strictly overrides any conflicting clause in the Global Employee Handbook or Global Leave Policies for UK employees.
================================================================================

Section 1.1 - Statutory & Company Maternity Leave (UK)
UK employees are entitled to 52 weeks of Statutory Maternity Leave (26 weeks Ordinary + 26 weeks Additional Maternity Leave):
- Statutory Maternity Pay (SMP): Paid for up to 39 weeks (90% of average weekly earnings for first 6 weeks, statutory rate thereafter).
- Company Enhanced Maternity Pay:
  * Grades 1 to 3: SMP plus 6 weeks full base pay top-up.
  * Grades 4 to 6: SMP plus 18 weeks full base pay top-up.
  * Grade 7: Full base salary for 26 weeks.
Eligibility requires 26 weeks continuous service into the qualifying week (15th week before expected week of childbirth).

Section 1.2 - UK Paternity & Shared Parental Leave
Statutory Paternity Leave: 2 consecutive weeks paid at statutory rate or 90% of weekly earnings (whichever is lower).
Shared Parental Leave (SPL): Eligible parents may share up to 50 weeks of leave and 37 weeks of pay during the child's first year.

Section 2.1 - UK Annual Leave & Working Time Regulations
UK employees receive 25 days paid annual leave plus 8 UK statutory bank holidays (total 33 days).
In accordance with UK Working Time Regulations, at least 4 weeks (20 days) must be taken within the leave year. Up to 5 days of untaken contractual leave may be carried over with Director consent.

Section 3.1 - UK Statutory Notice Period Overrides
Notice periods in the UK entity supersede general handbook rules:
- During probation: 1 week notice.
- Confirmed Grades 1 to 3: 4 weeks (1 month) notice.
- Confirmed Grades 4 to 6: 12 weeks (3 months) notice.
- Confirmed Grade 7: 6 months notice.
Statutory minimum notice under Employment Rights Act 1996 § 86 (1 week per completed year of service, up to 12 weeks) applies if greater than contractual notice.
"""

